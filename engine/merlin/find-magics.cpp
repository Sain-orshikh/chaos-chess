// Offline deterministic search. No borrowed magic constants or runtime brute
// force.
#include "sliders.h"
#include <array>
#include <cstdio>
#include <cstdlib>
using namespace sliders;
uint64_t seed = 0x4d65726c696e3031ULL;
uint64_t random64() {
  seed += 0x9e3779b97f4a7c15ULL;
  auto x = seed;
  x = (x ^ (x >> 30)) * 0xbf58476d1ce4e5b9ULL;
  x = (x ^ (x >> 27)) * 0x94d049bb133111ebULL;
  return x ^ (x >> 31);
}
int main() {
  std::puts("// Generated by find-magics.cpp; a8=bit 0. Do not "
            "hand-edit.\n#pragma once\n#include <cstdint>");
  for (bool diagonal : {false, true}) {
    std::printf("inline constexpr uint64_t %sMagics[64]={\n",
                diagonal ? "bishop" : "rook");
    for (int sq = 0; sq < 64; sq++) {
      auto mask = relevant(sq, diagonal);
      int bits = __builtin_popcountll(mask), count = 1 << bits;
      std::array<Bits, 4096> occupancies{}, attacks{}, used{};
      std::array<unsigned, 4096> stamp{};
      Bits sub = 0;
      int n = 0;
      do {
        occupancies[n] = sub;
        attacks[n++] = ray(sq, sub, diagonal);
        sub = (sub - mask) & mask;
      } while (sub);
      bool found = false;
      Bits magic = 0;
      for (unsigned attempt = 1; attempt < 100000000; attempt++) {
        magic = random64() & random64() & random64();
        if (__builtin_popcountll((mask * magic) & 0xff00000000000000ULL) < 6)
          continue;
        bool valid = true;
        for (int i = 0; i < count; i++) {
          unsigned index = (occupancies[i] * magic) >> (64 - bits);
          if (stamp[index] != attempt) {
            stamp[index] = attempt;
            used[index] = attacks[i];
          } else if (used[index] != attacks[i]) {
            valid = false;
            break;
          }
        }
        if (valid) {
          found = true;
          break;
        }
      }
      if (!found) {
        std::fprintf(stderr, "No magic: %d %d\n", diagonal, sq);
        return 1;
      }
      std::printf("0x%016llxULL%s\n", (unsigned long long)magic,
                  sq == 63 ? "" : ",");
    }
    std::puts("};");
  }
}
